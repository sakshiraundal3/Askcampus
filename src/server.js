require('dotenv').config();
const express=require('express');
const cors=require('cors');
const helmet=require('helmet');
const rateLimit=require('express-rate-limit');
const path=require('path');
const db=require('./config/db');
const app=express();
app.use(helmet({contentSecurityPolicy:false}));
app.use(cors({origin:process.env.CLIENT_ORIGIN||'http://localhost:5000'}));
app.use(express.json({limit:'1mb'}));
app.use(rateLimit({windowMs:15*60*1000,limit:150,standardHeaders:'draft-7',legacyHeaders:false}));
app.use(express.static(path.join(__dirname,'../public')));
app.get('/api/health',async(req,res)=>{try{await db.query('SELECT 1');res.json({status:'ok',database:'connected'});}catch{res.status(503).json({status:'error',database:'unavailable'});}});
app.use('/api/auth',require('./routes/authRoutes'));
app.use('/api/faqs',require('./routes/faqRoutes'));
app.use('/api/chat',require('./routes/chatRoutes'));
app.use((req,res)=>res.status(404).json({error:'Route not found'}));
app.use((err,req,res,next)=>{console.error(err);res.status(500).json({error:process.env.NODE_ENV==='production'?'Internal server error':err.message});});
const port=process.env.PORT||5000;
app.listen(port,()=>console.log(`AskCampus running at http://localhost:${port}`));
